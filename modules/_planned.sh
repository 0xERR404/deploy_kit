#!/bin/bash
# =============================================================================
# _planned.sh — общая заглушка для пунктов меню из roadmap, ещё не
# реализованных (Actual Budget, Vikunja, Navidrome, Chyrp Lite, Syncthing,
# Backup — см. бриф проекта). НЕ модуль пайплайна: нет своих шагов и
# STATEFILE, ничего не устанавливает и не меняет.
#
# Один и тот же файл переиспользуется для всех ещё не готовых пунктов —
# именно поэтому название сервиса передаётся отдельно, через переменную
# PLANNED_NAME, а не зашито в текст (source читает файл целиком, значит
# переменная, выставленная menu.sh ДО source, будет здесь видна).
# Если PLANNED_NAME не задан (например, кто-то запустил файл напрямую или
# по ошибке подключил без разметки) — используем нейтральную подпись,
# чтобы вывод оставался осмысленным в любом случае.
#
# Позиции в меню зарезервированы ЗАРАНЕЕ (9-14) под конкретный roadmap
# проекта — так итоговая сводка (модуль 15) с самого начала находится на
# постоянном месте и не будет сдвигаться по мере добавления новых
# сервис-модулей один за другим.
# =============================================================================

echo "${BOLD}${CYAN}==========================================================================="
echo "  ${PLANNED_NAME:-Этот модуль} — В РАЗРАБОТКЕ"
echo "===========================================================================${NC}"
echo ""
echo "${YELLOW}[?]${NC} Модуль ещё не реализован — позиция в меню зарезервирована заранее"
echo "    под этот сервис (см. roadmap проекта), чтобы номер пункта не менялся"
echo "    при добавлении новых модулей."
echo ""
